"""Статусы заявки: один список кодов и одна русская подпись к каждому.

Списков было три и они разошлись. Правка заявки разрешала «Квалифицирована», а
карточка клиента такого кода не знала и печатала в плашку сырое `qualified`.
Симметрично «Спам» был у сервера, но его не было ни в подписях фронта, ни в
плашках отбора.

Поэтому и коды, и подписи живут здесь, а модуль заявок и карточка клиента
берут их отсюда. Порядок словаря — это порядок жизни заявки: он же используется
для плашек отбора, чтобы «Новая» не оказалась после «Отказа».
"""

from __future__ import annotations

#: Код → подпись, которую читает менеджер. Порядок значим.
LEAD_STATUS_LABELS: dict[str, str] = {
    "new": "Ждёт ответа",
    "in_progress": "В работе",
    "qualified": "Квалифицирована",
    "converted": "Стала заказом",
    "rejected": "Отказ",
    "spam": "Спам",
}

#: Коды, которые разрешено ставить руками.
LEAD_STATUSES: tuple[str, ...] = tuple(LEAD_STATUS_LABELS)

#: Статусы, по которым заказа уже не будет. Расчёт с таким статусом перестаёт
#: считаться ждущим ответа: ждать нечего, а закрыть его было больше нечем.
CLOSED_LEAD_STATUSES: frozenset[str] = frozenset({"rejected", "spam"})


def lead_status_label(code: str | None) -> str:
    """Русская подпись статуса. Незнакомый код возвращаем как есть.

    Не «Неизвестно»: если в базе однажды окажется чужой код, менеджеру полезнее
    увидеть его буквально и сказать об этом, чем гадать, что за статус скрыт.
    """
    if not code:
        return ""
    return LEAD_STATUS_LABELS.get(code, code)
