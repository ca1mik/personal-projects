from __future__ import annotations

# Типы работ, которые студия называет вслух. Список — подсказка для выпадающего
# списка, а не ограничение: поле `kind` строковое, и заказчик заводит свой тип,
# если появится новая операция.
PRICE_ITEM_KINDS: dict[str, str] = {
    "milling": "Фрезеровка",
    "veneer": "Шпон",
    "soap": "Мыло",
    "paint": "Эмаль",
    "film": "Плёнка ПВХ",
    "board": "Плита",
    "edge": "Кромка",
    "service": "Услуга",
    "other": "Прочее",
}

# Производственные направления студии.
#
# Тот же список, что миграция 0007 заводит в таблицу `production_directions`:
# направления живут в БД и заказчик правит их из админки, но приём заявки и
# сборка номера обращаются к ним до всякого запроса. Расхождение этих двух
# списков и было причиной того, что в форме заявки выбирали «Плёнка ПВХ», а
# направление «ПВХ» в базе так и оставалось пустым. За совпадением следит
# `app/tests/test_order_number_suffix.py`.
PRODUCTION_DIRECTION_NAMES: dict[str, str] = {
    "enamel": "Эмаль",
    "pvc": "ПВХ",
    "veneer": "Шпон",
}

# Буква в номере заказа по направлению.
#
# Эмаль без буквы — так у студии заведено: «1024» и есть эмаль.
DIRECTION_NUMBER_SUFFIXES: dict[str, str] = {
    "enamel": "",
    "pvc": "П",
    "veneer": "Ш",
}

# Направление → тип работ прайса.
#
# Одно и то же покрытие называлось в двух справочниках по-разному: направление
# «pvc» и тип работ «film», направление «enamel» и тип «paint». Из-за этого
# номенклатура, заведённая из заявки, не соотносилась с направлением заявки, а
# буква номера считалась по двум несогласованным таблицам. Связь держим здесь
# одну, в обе стороны.
DIRECTION_PRICE_KINDS: dict[str, str] = {
    "enamel": "paint",
    "pvc": "film",
    "veneer": "veneer",
}

# Буква в номере заказа по типу работ.
#
# Заказчик: «в зависимости от фрезы, мыла, шпона и т.д. присваивался к цифрам
# буква». Буквы направлений сюда переносятся автоматически — чтобы «pvc» и
# «film» не могли когда-нибудь дать разные буквы. Отдельно перечислены только
# операции, у которых своего направления нет.
#
# Типы, которых здесь нет, дают номер без буквы: выдумывать за студию
# обозначения нельзя, а лишняя буква в номере хуже её отсутствия — по ней в
# цеху ищут пачку.
PRICE_ITEM_NUMBER_SUFFIXES: dict[str, str] = {
    **{kind: DIRECTION_NUMBER_SUFFIXES[code] for code, kind in DIRECTION_PRICE_KINDS.items()},
    "milling": "Ф",
    "soap": "М",
}


def kind_number_suffix(code: str) -> str:
    """Буква номера по коду направления или типу работ.

    Принимает обе записи одного и того же покрытия («pvc» и «film»): номер
    собирают и по направлению заявки, и по типу работ её строк, а буква должна
    получаться одна. Пусто — номер остаётся числом.
    """
    if code in DIRECTION_NUMBER_SUFFIXES:
        return DIRECTION_NUMBER_SUFFIXES[code]
    return PRICE_ITEM_NUMBER_SUFFIXES.get(code, "")


def direction_price_kind(code: str) -> str:
    """Тип работ прайса для направления. Пусто — направление без своего типа.

    Заказчик добавляет направления сам («Акрил»), и типа работ для нового
    направления в прайсе может не быть. Тогда номенклатура заводится без типа,
    а не под чужим: пустая графа в отчёте «по видам обработки» честнее, чем
    акриловые фасады, посчитанные как эмаль.
    """
    return DIRECTION_PRICE_KINDS.get(code, "")


# Типовой срок по типу работ, в рабочих днях от приёма заявки.
#
# Заказчик назвал только мыло — 14 дней. Остальные типы стоят на том же сроке:
# это подстановка, а не правило, и менеджер меняет дату при создании заявки.
# Выдумывать за студию разные сроки нельзя — по ним она отвечает перед клиентом.
#
# Дни календарные: клиенту называют дату, а не «десять рабочих».
PRICE_ITEM_LEAD_TIME_DAYS: dict[str, int] = {
    "soap": 14,
    "milling": 14,
    "paint": 14,
    "film": 14,
    "veneer": 14,
}

#: Срок для типа, которого нет в списке, — столько же.
DEFAULT_LEAD_TIME_DAYS = 14


def kind_lead_time_days(code: str) -> int:
    """Сколько дней занимает работа этого типа."""
    return PRICE_ITEM_LEAD_TIME_DAYS.get(code, DEFAULT_LEAD_TIME_DAYS)


# Здесь была константа `PRODUCTION_KINDS` — типы работ целых направлений.
# После того как выбор направления стал отдавать коды направлений, а не типы
# работ, её перестали использовать: тот же список собирается ниже, в
# `production_kind_options`, вместе с подписями. Оставлять вторую копию
# справочника незачем — именно на паре несогласованных списков и разъезжались
# направление заявки и тип её номенклатуры.


def production_kind_options() -> list[dict[str, str]]:
    """Направления для выбора при приёме заявки, в порядке для списка.

    В `code` едет код направления — ровно тот, что принимает приём заявки в
    поле `direction_code`. Раньше здесь были коды типов работ («film»), форма
    отправляла их как тип номенклатуры, а направление у заявки не проставлялось
    вообще: все отборы и отчёты по направлениям выходили пустыми.

    `kind` рядом — тип работ прайса для того же направления: под ним заводится
    номенклатура из артикулов, набранных в заявке руками.
    """
    return [
        {"code": code, "label": name, "kind": direction_price_kind(code)}
        for code, name in PRODUCTION_DIRECTION_NAMES.items()
    ]


# Единицы измерения. «sqm» считает сумму по площади, остальные — по количеству.
PRICE_ITEM_UNITS: dict[str, str] = {
    "sqm": "м²",
    "pcs": "шт",
    "m": "пог. м",
}

AREA_UNIT = "sqm"


def kind_label(code: str) -> str:
    """Русское название типа. Незнакомый код показываем как есть."""
    return PRICE_ITEM_KINDS.get(code, code)


def unit_label(code: str) -> str:
    return PRICE_ITEM_UNITS.get(code, code)
